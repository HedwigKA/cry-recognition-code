"""Train the final Stage 1 and Stage 2 models on all data and export them for edge deployment.

Cross-validation in stage1.py / stage2.py only measures performance; this script produces the
deployable models in models/:
  stage1_cry.keras / stage1_cry_int8.tflite / stage1_cry_model.h / stage1_norm.json
  stage2_reason.keras / stage2_reason_int8.tflite / stage2_reason_model.h / stage2_norm.json
"""
import json
import os

import numpy as np
import pandas as pd
import tensorflow as tf

from features import SILENCE_DBFS
from stage2 import REASONS
from train_lib import FLOOR_DB, Scaler, fit, predict_int8, to_int8

SEED = 42
STAGE1_LABELS = ["non-cry", "cry", "silence"]
OUT = "models"


def c_array(data: bytes, name: str, comment: str) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    body = ",\n  ".join(rows)
    return (f"// Generated by export_model.py - {comment} (int8 TFLite)\n"
            f"#pragma once\n\nalignas(16) const unsigned char {name}[] = {{\n  {body}\n}};\n"
            f"const unsigned int {name}_len = {len(data)};\n")


def export_bundle(prefix: str, array_name: str, comment: str, model, Xs: np.ndarray,
                  sc: Scaler, labels: list[str], extra_meta: dict):
    keras_path = os.path.join(OUT, f"{prefix}.keras")
    tfl_path = os.path.join(OUT, f"{prefix}_int8.tflite")
    hdr_path = os.path.join(OUT, f"{prefix}_model.h")
    norm_path = os.path.join(OUT, f"{prefix.split('_')[0]}_norm.json")

    model.save(keras_path)
    tfl = to_int8(model, Xs)
    with open(tfl_path, "wb") as f:
        f.write(tfl)
    with open(hdr_path, "w") as f:
        f.write(c_array(tfl, array_name, comment))

    it = tf.lite.Interpreter(model_content=tfl)
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    norm = dict(
        labels=labels,
        floor_db=FLOOR_DB,
        mean=sc.mu,
        std=sc.sd,
        input_shape=[98, 40],
        input_scale=float(inp["quantization"][0]),
        input_zero_point=int(inp["quantization"][1]),
        output_scale=float(out["quantization"][0]),
        output_zero_point=int(out["quantization"][1]),
        silence_dbfs=SILENCE_DBFS,
        **extra_meta,
        feature="8 kHz mono, 1 s window / 0.5 s hop, 40-band log-mel, 25 ms frame / 10 ms stride, NFFT 256",
        note="x_int8 = round(((max(logmel, floor_db) - mean) / std) / input_scale + input_zero_point)",
    )
    with open(norm_path, "w") as f:
        json.dump(norm, f, indent=2)

    agree = (predict_int8(tfl, Xs).argmax(1) == model.predict(Xs, batch_size=1024, verbose=0).argmax(1)).mean()
    print(f"[{prefix}] int8 size = {len(tfl) / 1024:.1f} KB, int8/float agreement = {agree:.1%}", flush=True)


def main():
    os.makedirs(OUT, exist_ok=True)
    d = np.load("data.npz")
    X, clip_id, db = d["X"], d["clip_id"], d["dbfs"]
    df = pd.read_csv("data_clips.csv", keep_default_na=False)

    # --- Stage 1: cry / non-cry / silence on all windows ---
    loud = db >= SILENCE_DBFS
    y1 = np.where(~loud, 2, df["cry"].values[clip_id])
    clip_max = np.full(len(df), -np.inf)
    np.maximum.at(clip_max, clip_id, db)
    quiet_clip = clip_max[clip_id] < SILENCE_DBFS
    y1[quiet_clip] = df["cry"].values[clip_id[quiet_clip]]

    sc1 = Scaler().fit(X)
    Xs1 = sc1(X)
    print("Stage 1: training on all windows:", len(Xs1), flush=True)
    m1 = fit(Xs1, y1, len(STAGE1_LABELS), df["group"].values[clip_id], class_weight=True, seed=SEED)
    export_bundle(
        prefix="stage1_cry",
        array_name="g_stage1_cry_model",
        comment="stage 1 cry detector",
        model=m1,
        Xs=Xs1,
        sc=sc1,
        labels=STAGE1_LABELS,
        extra_meta=dict(device_rule="alarm if mean P(cry) of 3 consecutive windows >= 0.80"),
    )

    # --- Stage 2: 5 cry reasons (class-weighted) on Donate-a-Cry non-silent windows ---
    dac = df[df["source"] == "dac"].reset_index(drop=True)
    keep = np.isin(clip_id, dac["clip_id"]) & ((db >= SILENCE_DBFS) | (clip_max[clip_id] < SILENCE_DBFS))
    X2, cid2 = X[keep], clip_id[keep]
    reason_map = {r: i for i, r in enumerate(REASONS)}
    clip_reason = df["reason"].map(reason_map).values
    y2 = clip_reason[cid2].astype(np.int32)
    g2 = df["group"].values[cid2]

    sc2 = Scaler().fit(X2)
    Xs2 = sc2(X2)
    print("Stage 2: training on Donate-a-Cry windows:", len(Xs2), flush=True)
    m2 = fit(Xs2, y2, len(REASONS), g2, class_weight=True, epochs=30, seed=SEED)
    export_bundle(
        prefix="stage2_reason",
        array_name="g_stage2_reason_model",
        comment="stage 2 cry reason classifier",
        model=m2,
        Xs=Xs2,
        sc=sc2,
        labels=REASONS,
        extra_meta=dict(fusion_note="Combine window-mean P_audio(reason) with incubator sensor context weights"),
    )
    print("saved all models to", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
