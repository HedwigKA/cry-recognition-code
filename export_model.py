"""Train the final stage 1 model (cry / non-cry / silence) on all data and export it for the device.

Cross-validation in stage1.py only measures performance; this script produces the deployable model.
Outputs (in models/):
  stage1_cry.keras        float32 Keras model
  stage1_cry_int8.tflite  full-integer TFLite model (int8 input/output)
  stage1_cry_model.h      C array of the .tflite file for TFLite Micro
  stage1_norm.json        normalisation + quantisation parameters needed on the device
"""
import json
import os

import numpy as np
import pandas as pd

from features import SILENCE_DBFS
from train_lib import FLOOR_DB, Scaler, fit, predict_int8, to_int8

SEED = 42
LABELS = ["non-cry", "cry", "silence"]
OUT = "models"


def c_array(data: bytes, name: str) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    body = ",\n  ".join(rows)
    return (f"// Generated by export_model.py - stage 1 cry detector (int8 TFLite)\n"
            f"#pragma once\n\nalignas(16) const unsigned char {name}[] = {{\n  {body}\n}};\n"
            f"const unsigned int {name}_len = {len(data)};\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    d = np.load("data.npz")
    X, clip_id, db = d["X"], d["clip_id"], d["dbfs"]
    df = pd.read_csv("data_clips.csv", keep_default_na=False)

    # same window labels as stage1.py
    loud = db >= SILENCE_DBFS
    y = np.where(~loud, 2, df["cry"].values[clip_id])
    clip_max = np.full(len(df), -np.inf)
    np.maximum.at(clip_max, clip_id, db)
    quiet_clip = clip_max[clip_id] < SILENCE_DBFS
    y[quiet_clip] = df["cry"].values[clip_id[quiet_clip]]

    sc = Scaler().fit(X)
    Xs = sc(X)
    print("training on all windows:", len(Xs), flush=True)
    model = fit(Xs, y, 3, df["group"].values[clip_id], seed=SEED)
    model.save(os.path.join(OUT, "stage1_cry.keras"))

    tfl = to_int8(model, Xs)
    with open(os.path.join(OUT, "stage1_cry_int8.tflite"), "wb") as f:
        f.write(tfl)
    with open(os.path.join(OUT, "stage1_cry_model.h"), "w") as f:
        f.write(c_array(tfl, "g_stage1_cry_model"))

    import tensorflow as tf
    it = tf.lite.Interpreter(model_content=tfl)
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    norm = dict(labels=LABELS, floor_db=FLOOR_DB, mean=sc.mu, std=sc.sd,
                input_shape=[98, 40], input_scale=float(inp["quantization"][0]),
                input_zero_point=int(inp["quantization"][1]),
                output_scale=float(out["quantization"][0]),
                output_zero_point=int(out["quantization"][1]),
                silence_dbfs=SILENCE_DBFS, device_rule="alarm if mean P(cry) of 3 consecutive windows >= 0.80",
                feature="8 kHz mono, 1 s window / 0.5 s hop, 40-band log-mel, 25 ms frame / 10 ms stride, NFFT 256",
                note="x_int8 = round(((max(logmel, floor_db) - mean) / std) / input_scale + input_zero_point)")
    with open(os.path.join(OUT, "stage1_norm.json"), "w") as f:
        json.dump(norm, f, indent=2)

    # sanity check: int8 vs float agreement on training windows (not a performance estimate)
    agree = (predict_int8(tfl, Xs).argmax(1) == model.predict(Xs, batch_size=1024, verbose=0).argmax(1)).mean()
    print(f"int8 size = {len(tfl) / 1024:.1f} KB, int8/float agreement = {agree:.1%}")
    print("saved to", os.path.abspath(OUT))


if __name__ == "__main__":
    main()

